// Build script: embed the maternal-health knowledge base into api/_lib/embeddings.js.
//
// Usage:
//   GEMINI_API_KEY=... node scripts/build-embeddings.mjs
//   (or put GEMINI_API_KEY=... in .env.local and just run `node scripts/build-embeddings.mjs`)
//
// It reads knowledge/maternal-health.md, splits it into one chunk per "## " section,
// embeds each with Gemini text-embedding-004 (RETRIEVAL_DOCUMENT), and writes the vectors
// to api/_lib/embeddings.js as a plain ES module (no JSON-import assertions needed at
// runtime). Re-run this whenever you edit the knowledge base.

import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'
import { GoogleGenerativeAI } from '@google/generative-ai'

const __dirname = dirname(fileURLToPath(import.meta.url))
const ROOT = join(__dirname, '..')
const SOURCE = join(ROOT, 'knowledge', 'maternal-health.md')
const OUT = join(ROOT, 'api', '_lib', 'embeddings.js')
const EMBED_MODEL = 'gemini-embedding-001'

// --- Resolve the API key (env var first, then a simple .env.local parse) -------------
function loadApiKey() {
  if (process.env.GEMINI_API_KEY) return process.env.GEMINI_API_KEY
  const envPath = join(ROOT, '.env.local')
  if (existsSync(envPath)) {
    for (const line of readFileSync(envPath, 'utf8').split('\n')) {
      const m = line.match(/^\s*GEMINI_API_KEY\s*=\s*(.+?)\s*$/)
      if (m) return m[1].replace(/^["']|["']$/g, '')
    }
  }
  return null
}

// --- Split the markdown into self-contained chunks (one per "## " heading) -----------
function chunkMarkdown(md) {
  const chunks = []
  let current = null
  for (const rawLine of md.split('\n')) {
    const headingMatch = rawLine.match(/^##\s+(.+?)\s*$/)
    if (headingMatch) {
      if (current) chunks.push(current)
      current = { heading: headingMatch[1], lines: [] }
    } else if (current) {
      current.lines.push(rawLine)
    }
  }
  if (current) chunks.push(current)

  return chunks
    .map(({ heading, lines }) => ({
      heading,
      // Collapse the hard-wrapped paragraph into clean single-spaced text.
      text: lines.join(' ').replace(/\s+/g, ' ').trim(),
    }))
    .filter((c) => c.text.length > 0)
}

async function main() {
  const apiKey = loadApiKey()
  if (!apiKey) {
    console.error('Missing GEMINI_API_KEY. Set it as an env var or add it to .env.local.')
    process.exit(1)
  }

  const md = readFileSync(SOURCE, 'utf8')
  const chunks = chunkMarkdown(md)
  console.log(`Embedding ${chunks.length} chunks from ${SOURCE} with ${EMBED_MODEL}...`)

  const genAI = new GoogleGenerativeAI(apiKey)
  const model = genAI.getGenerativeModel({ model: EMBED_MODEL })

  const records = []
  for (let i = 0; i < chunks.length; i++) {
    const { heading, text } = chunks[i]
    const res = await model.embedContent({
      content: { parts: [{ text }] },
      taskType: 'RETRIEVAL_DOCUMENT',
      title: heading,
    })
    const embedding = res.embedding?.values
    if (!embedding) throw new Error(`No embedding returned for chunk "${heading}"`)
    records.push({ id: i, heading, text, embedding })
    console.log(`  [${i + 1}/${chunks.length}] ${heading} (${embedding.length} dims)`)
  }

  const header =
    '// AUTO-GENERATED by scripts/build-embeddings.mjs — do not edit by hand.\n' +
    `// Source: knowledge/maternal-health.md  |  Model: ${EMBED_MODEL}  |  ${records.length} chunks\n`
  writeFileSync(OUT, `${header}export default ${JSON.stringify(records)}\n`)
  console.log(`Wrote ${records.length} embeddings to ${OUT}`)
}

main().catch((err) => {
  console.error('build-embeddings failed:', err)
  process.exit(1)
})
